"""
Vision-processing branch of Fig. 13: extracts the supervisory labels
used to train the WiFi-signal branch.

- Mask label: Mask R-CNN [15] (He et al. 2017), exactly as stated in
  §4.2: "We use Mask RCNN [15] to obtain body part mask segmentation."
  torchvision ships a native Mask R-CNN (maskrcnn_resnet50_fpn), the
  same architecture as reference [15].

- Keypoint label: HRNet [42] (Sun et al. 2019), exactly as stated in
  §4.2: "... and HRNet [42] to extract person keypoints." torchvision
  does NOT include HRNet. This module calls HRNet through `mmpose`
  (OpenMMLab), which distributes the official HRNet COCO checkpoints,
  because no HRNet implementation exists in the PyTorch/torchvision
  standard library. `mmpose` must be installed separately.
"""

from __future__ import annotations

import numpy as np
import torch
from torchvision.models.detection import (
    MaskRCNN_ResNet50_FPN_Weights,
    maskrcnn_resnet50_fpn,
)

try:
    from mmpose.apis import inference_topdown
    from mmpose.apis import init_model as init_pose_model

    _MMPOSE_AVAILABLE = True
except ImportError:
    _MMPOSE_AVAILABLE = False


class MaskLabelExtractor:
    """Wraps Mask R-CNN [15] to produce the mask ground truth."""

    def __init__(self, device: str = "cuda", score_thresh: float = 0.5):
        weights = MaskRCNN_ResNet50_FPN_Weights.DEFAULT
        self.model = maskrcnn_resnet50_fpn(weights=weights).to(device).eval()
        self.device = device
        self.score_thresh = score_thresh

    @torch.no_grad()
    def extract(self, frame_rgb_uint8: np.ndarray) -> np.ndarray:
        """
        frame_rgb_uint8: (H, W, 3) uint8 RGB video frame.
        Returns: (H, W) float32 mask in [0, 1], the union of all
        detected person instances above score_thresh. The DNN's mask
        head (Fig. 13, Fig. 14) is supervised with a single
        foreground/background silhouette, not per-instance masks.
        """
        tensor = torch.from_numpy(frame_rgb_uint8).permute(2, 0, 1).float().div(255.0)
        tensor = tensor.unsqueeze(0).to(self.device)
        output = self.model(tensor)[0]
        h, w = frame_rgb_uint8.shape[:2]
        mask = np.zeros((h, w), dtype=np.float32)
        for label, score, m in zip(output["labels"], output["scores"], output["masks"]):
            if int(label) == 1 and float(score) >= self.score_thresh:  # COCO label 1 = person
                mask = np.maximum(mask, m[0].cpu().numpy())
        return mask


class KeypointLabelExtractor:
    """Wraps HRNet [42] (via mmpose) to produce per-person keypoints."""

    def __init__(self, hrnet_config: str, hrnet_checkpoint: str, device: str = "cuda"):
        if not _MMPOSE_AVAILABLE:
            raise ImportError(
                "mmpose is required for HRNet keypoint extraction, as used in "
                "the paper (§4.2, ref [42]). Install with the OpenMMLab stack "
                "(mmpose, mmcv, mmdet, mmengine), then pass an HRNet COCO "
                "config/checkpoint pair from the mmpose model zoo."
            )
        self.model = init_pose_model(hrnet_config, hrnet_checkpoint, device=device)

    def extract(self, frame_rgb_uint8: np.ndarray, person_boxes: np.ndarray) -> np.ndarray:
        """
        person_boxes: (N, 4) xyxy boxes -- HRNet is a top-down pose
        estimator and requires person boxes as input. This pipeline
        reuses the Mask R-CNN detections already computed for the
        mask label (see data/build_labels.py: `_boxes_from_mask`),
        since the paper's "Vision Processing" box (Fig. 13) does not
        describe a separate person detector for HRNet.
        Returns: (N, num_keypoints, 3) array of (x, y, score) per person.
        """
        results = inference_topdown(self.model, frame_rgb_uint8, bboxes=person_boxes)
        keypoints = np.stack([r.pred_instances.keypoints[0] for r in results], axis=0)
        scores = np.stack([r.pred_instances.keypoint_scores[0] for r in results], axis=0)
        return np.concatenate([keypoints, scores[..., None]], axis=-1)


def keypoints_to_heatmap(
    keypoints_xy: np.ndarray,
    heatmap_h: int,
    heatmap_w: int,
    frame_h: int,
    frame_w: int,
    sigma: float = 2.0,
) -> np.ndarray:
    """
    Rasterize one person's (x, y) keypoints into per-joint Gaussian
    heatmaps at the DNN's output resolution (48 x 64, §4.1.2). The
    supervisory signal is "heatmaps generated by the vision process
    network" (§3.2.2).
    keypoints_xy: (num_keypoints, 2) in original frame pixel coords.
    """
    num_kp = keypoints_xy.shape[0]
    heatmaps = np.zeros((num_kp, heatmap_h, heatmap_w), dtype=np.float32)
    sx, sy = heatmap_w / frame_w, heatmap_h / frame_h
    yy, xx = np.mgrid[0:heatmap_h, 0:heatmap_w]
    for k in range(num_kp):
        x, y = keypoints_xy[k, 0] * sx, keypoints_xy[k, 1] * sy
        if x < 0 or y < 0:
            continue
        heatmaps[k] = np.exp(-((xx - x) ** 2 + (yy - y) ** 2) / (2 * sigma ** 2))
    return heatmaps